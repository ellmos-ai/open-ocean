def _cache(tmp_path: Path, *, age_minutes: float = 1, rows=None, count=None, header=None, stamp=None) -> Path:
    rows = [(f"{PRIVATE_PATH}\\LOCK.txt", "build", "Lukas (User)", "2026-10-01T10:00", "?"),
            (f"{PRIVATE_PATH}\\LOCK.until.x.txt (legacy)", "x", "owner", "2026-10-01T10:00", "3h")] if rows is None else rows
    stamp = stamp or (datetime.now() - timedelta(minutes=age_minutes)).replace(microsecond=0).isoformat()
    lines = [header or "<!-- AUTO-GENERATED by lock_scan.py --write-cache. DO NOT edit manually. -->", "",
             f"As of: {stamp}", "", f"Active locks: {len(rows) if count is None else count}", "",
             "| Path | scope | owner | created | remaining |", "|---|---|---|---|---|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows] or ["| _(no active locks)_ | | | | |"]
    path = tmp_path / "LOCK-CACHE.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


