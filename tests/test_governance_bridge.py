def _entry(entry_id, kind="policy", privacy="public", **extra):
    return {"id": entry_id, "kind": kind, "title": f"Titel {entry_id}", "scope": "global", "version": "1",
            "privacy": privacy, "status": "active", "source": {"uri": PRIVATE_PATH + "\\text.md"},
            "hash": {"value": "ab" * 32}, **extra}


class _Registry:
    def __init__(self, entries, path: Path, mutate=False):
        self.entries, self.path, self.mutate = entries, path, mutate

    def search(self, query="", *, scope=None, consumer=None, kind=None):
        if self.mutate:
            self.path.write_text('{"changed": true}')
        return [e for e in self.entries if (not kind or e["kind"] == kind) and query in e["title"]]

    def verify(self):
        return {"checks": [{"id": e["id"], "state": "ok"} for e in self.entries]}

    def resolve(self, *, scope, consumer=None, query=""):
        return {"status": "resolved", "reason": "single", "selected": self.entries[0],
                "candidates": self.entries, "interaction_mode": None}


PROVIDER = {"id": "policy-registry", "version": "0.2.3", "source_commit": "c" * 40,
            "repository": gov.REPOSITORY, "verified": True}


def _registry_reader(tmp_path, entries, **options):
    path = tmp_path / "registry.json"
    path.write_text('{"entries": []}')
    registry = _Registry(entries, path, **options)
    return lambda **kwargs: gov.observe(registry=registry, registry_path=path, provider=PROVIDER, **kwargs)


