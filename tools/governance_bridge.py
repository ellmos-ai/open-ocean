"""Read-only governance reads for the GUI, contract-equal to BACH (bach.policy-registry.v1, lock-cache feed).

Two sources only, both bound explicitly by the bridge configuration: the host lock-cache feed (LOCK-CACHE.md,
never a filesystem scan) and a verified policy-registry checkout. Whatever is not bound answers an honest
"unavailable" with a machine-readable code; nothing here fabricates data or writes anything.
"""
from __future__ import annotations

import hashlib
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable

try:
    from .catalog_projection import _read_bytes  # handle-bound, final-path-verified, size-limited read (#53)
except ImportError:  # direct entry point
    from catalog_projection import _read_bytes

LOCK_HEADER = "AUTO-GENERATED by lock_scan.py"
LOCK_STALE_SECONDS = 1800  # BACH unified_api.py: age > 30 min (or a clock more than 60 s ahead) is stale
MAX_LOCK_CACHE_BYTES = 1024 * 1024
MAX_LOCK_ROWS = 2000
MAX_CELL = 256
MAX_REGISTRY_BYTES = 16 * 1024 * 1024
MAX_ENTRIES = 5000  # more than this is an error, never a silent cut (count would claim completeness)
REGISTRY_SCHEMA = "bach.policy-registry.v1"
REPOSITORY = "https://github.com/ellmos-ai/policy-registry"
POINTER_FIELDS = ("id", "kind", "title", "scope", "version", "privacy", "status", "adoption", "priority",
                  "precedence", "valid_from", "valid_until", "supersedes", "superseded_by")


class GovernanceUnavailable(RuntimeError):
    """Carries a BACH reason code such as policy_provider_not_configured."""


class GovernanceChanged(RuntimeError):
    pass


def _now() -> datetime:
    return datetime.now(timezone.utc)


def lock_cache_snapshot(cache: Path | None, *, now: datetime | None = None) -> dict[str, Any]:
    """Parse the generated lock-scan feed like BACH `_lock_cache_snapshot`; only filename and scope leave."""
    checked_at = (now or _now()).isoformat()
    unavailable = {"availability": "unavailable", "source": "lock_scan_cache", "checked_at": checked_at,
                   "scanned_at": None, "count": None, "locks": [], "error": "lock_cache_missing"}
    if cache is None:
        return unavailable
    try:
        # One handle: opened, identity-checked (no link out of its folder) and size-bounded while reading.
        lines = _read_bytes(cache, cache.parent, MAX_LOCK_CACHE_BYTES)[0].decode("utf-8").splitlines()
        if not lines or LOCK_HEADER not in lines[0]:
            raise ValueError("invalid_header")
        stamp = next(line.partition(": ")[2] for line in lines if line.startswith("As of: "))
        count = int(next(line.partition(": ")[2] for line in lines if line.startswith("Active locks: ")))
        scanned = datetime.fromisoformat(stamp)
        if scanned.tzinfo is None:
            scanned = scanned.astimezone()
        locks = []
        for line in lines:
            if (not line.startswith("| ") or line.startswith("| Path ") or line.startswith("|---")
                    or "_(no active locks)_" in line):
                continue
            cells = [cell.strip() for cell in line.strip("|").split("|")]
            if len(cells) != 5 or any(len(cell) > MAX_CELL for cell in cells) or len(locks) >= MAX_LOCK_ROWS:
                raise ValueError("invalid_row")
            name = Path(cells[0].replace("\\", "/").removesuffix(" (legacy)")).name
            locks.append({"name": name, "scope": cells[1], "type": "lock", "status": "active"})
        if count != len(locks):
            raise ValueError("count_mismatch")
        age = ((now or _now()) - scanned.astimezone(timezone.utc)).total_seconds()
        if age < -60 or age > LOCK_STALE_SECONDS:
            return {**unavailable, "availability": "stale", "scanned_at": scanned.isoformat(),
                    "error": "lock_cache_stale"}
        return {"availability": "available", "source": "lock_scan_cache", "checked_at": checked_at,
                "scanned_at": scanned.isoformat(), "count": count, "locks": locks, "error": None}
    except FileNotFoundError:
        return unavailable
    except (OSError, ValueError, StopIteration, UnicodeError):
        return {**unavailable, "error": "lock_cache_invalid"}


def pointer(entry: dict[str, Any], checks: dict[str, dict]) -> dict[str, Any]:
    """Allowlisted metadata only; local locations and policy text stay private (BACH `pointer`)."""
    item = {key: entry[key] for key in POINTER_FIELDS if key in entry}
    check = checks.get(entry["id"], {"state": "unchecked"})
    uri = str((entry.get("source") or {}).get("uri", ""))
    item["source"] = {"type": "remote-pointer" if "://" in uri else "local-pointer", "label": entry["id"]}
    declared = (entry.get("hash") or {}).get("value") or None
    item["source_sha256"] = declared
    item["source_state"] = check["state"]
    item["source_verified"] = check["state"] == "ok" and bool(declared)
    item["enforcement_verified"] = False
    return item


def _registry_bytes(path: Path) -> bytes:
    try:
        return _read_bytes(path, path.parent, MAX_REGISTRY_BYTES)[0]
    except FileNotFoundError:
        raise GovernanceUnavailable("policy_registry_missing") from None
    except ValueError:
        raise GovernanceUnavailable("policy_registry_too_large") from None
    except OSError:
        raise GovernanceUnavailable("policy_registry_unreadable") from None


def observe(*, registry_factory: Callable[[], Any], registry_path: Path, provider: dict[str, Any], scope: str | None = None,
            consumer: str | None = None, query: str = "", kind: str | None = None,
            effective: bool = False) -> dict[str, Any]:
    """bach.policy-registry.v1 from a bound registry; the file is hashed around the read through bound handles.

    Privacy default (operator decision): only entries with privacy == "public" leave this bridge. BACH returns all
    pointers; here nothing non-public is listed, counted or offered as a candidate, so count == len(entries).
    """
    path = Path(registry_path)
    try:
        before = hashlib.sha256(_registry_bytes(path)).hexdigest()
        registry = registry_factory()
        found = registry.search(query, scope=scope, consumer=consumer, kind=kind)
        public = [entry for entry in found if entry.get("privacy") == "public"]
        if len(public) > MAX_ENTRIES:
            raise GovernanceUnavailable("policy_registry_too_many_entries")
        checks = {item["id"]: item for item in registry.verify()["checks"]}
        resolved = registry.resolve(scope=scope, consumer=consumer, query=query) if effective else None
        if before != hashlib.sha256(_registry_bytes(path)).hexdigest():
            raise GovernanceChanged("policy_registry_changed_during_read")
        result = {
            "schema": REGISTRY_SCHEMA, "availability": "available", "observed_at": _now().isoformat(),
            "source": "policy-registry", "provider": provider, "registry_version": before, "read_only": True,
            "enforcement_verified": False, "entries": [pointer(entry, checks) for entry in public],
            "count": len(public),
            "source_verification_complete": bool(public) and all(
                checks.get(e["id"], {}).get("state") == "ok" and bool((e.get("hash") or {}).get("value"))
                for e in public),
            "decision_writer": {"id": "decision-clicker", "available": False,
                                "reason": "separate_explicit_adoption_required"}}
        if resolved is not None:
            selected = resolved.get("selected")
            visible = {entry["id"] for entry in public}
            result["effective"] = {
                "status": resolved["status"], "reason": resolved["reason"],
                "selected": pointer(selected, checks) if selected and selected.get("privacy") == "public" else None,
                "candidate_ids": [e["id"] for e in resolved.get("candidates", []) if e["id"] in visible],
                "interaction_mode": resolved.get("interaction_mode"),
                "interaction_source": resolved.get("interaction_source"),
                "governance_binding": resolved.get("governance_binding"),
                "external_effect_gates": resolved.get("external_effect_gates")}
        return result
    except (GovernanceUnavailable, GovernanceChanged):
        raise
    except Exception as exc:
        raise GovernanceUnavailable("policy_registry_read_failed") from exc


def decisions_view(result: dict) -> dict:
    return {**result, "decisions": result["entries"]}


def policies_view(result: dict) -> dict:
    """BACH adds name/desc/enforcement per policy or rule. BACH leaves `entries` unfiltered while overwriting `count`
    (count != len(entries)); here entries are filtered the same way, so bach.policy-registry.v1 stays self-consistent."""
    entries = [entry for entry in result["entries"] if entry["kind"] in {"policy", "rule"}]
    policies = [{**entry, "name": entry["title"], "desc": "Quellenmetadaten aus policy-registry",
                 "enforcement": "unverified"} for entry in entries]
    return {**result, "entries": entries, "policies": policies, "count": len(entries),
            "source_verification_complete": bool(entries) and all(e["source_verified"] for e in entries)}


def status_view(locks: dict, read_registry: Callable[..., dict] | None) -> dict:
    """BACH `/governance/status`: locks plus registry pointers; an unavailable source stays unknown."""
    try:
        if read_registry is None:
            raise GovernanceUnavailable("policy_provider_not_configured")
        governance = read_registry()
    except (GovernanceUnavailable, GovernanceChanged) as exc:
        governance = {"availability": "unavailable", "reason": str(exc), "entries": [], "count": None}
    entries = governance["entries"]
    return {
        "status": "observed" if locks["availability"] == "available" else "unknown",
        "timestamp": locks["checked_at"], "source": locks["source"], "availability": locks["availability"],
        "scanned_at": locks["scanned_at"], "error": locks["error"],
        "recent_decisions": [e for e in entries if e["kind"] == "decision"][:15],
        "active_locks": locks["locks"][:25], "lock_count": locks["count"],
        "policies": [e for e in entries if e["kind"] in {"policy", "rule"}],
        "policies_availability": governance["availability"], "policies_reason": governance.get("reason"),
        "policy_source": "policy-registry", "enforcement_verified": False}


def locks_view(locks: dict) -> dict:
    return {key: locks[key] for key in ("locks", "count", "availability", "source", "checked_at", "scanned_at", "error")}


